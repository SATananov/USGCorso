create or replace function public.list_my_content_items(
  target_section text
)
returns setof public.content_items
language sql
stable
security definer
set search_path = public
as $$
  select ci.*
  from public.content_items ci
  where ci.owner_user_id = auth.uid()
    and (
      target_section is null
      or ci.section_key = target_section
    )
  order by ci.updated_at desc;
$$;

create or replace function public.admin_list_content_items(
  target_section text,
  target_status text
)
returns table (
  id uuid,
  owner_user_id uuid,
  owner_display_name text,
  owner_username text,
  section_key text,
  content_type text,
  title text,
  body text,
  context_type text,
  context_id uuid,
  status text,
  moderation_note text,
  approved_by uuid,
  approved_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz,
  asset_count bigint
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'administrator access required' using errcode = '42501';
  end if;

  if target_status is not null
    and target_status not in ('pending', 'approved', 'rejected', 'archived') then
    raise exception 'invalid content status' using errcode = '22023';
  end if;

  return query
  select
    ci.id,
    ci.owner_user_id,
    p.display_name,
    p.username,
    ci.section_key,
    ci.content_type,
    ci.title,
    ci.body,
    ci.context_type,
    ci.context_id,
    ci.status,
    ci.moderation_note,
    ci.approved_by,
    ci.approved_at,
    ci.created_at,
    ci.updated_at,
    count(ca.id)
  from public.content_items ci
  left join public.profiles p
    on p.id = ci.owner_user_id
  left join public.content_assets ca
    on ca.content_item_id = ci.id
  where (
      target_section is null
      or ci.section_key = target_section
    )
    and (
      target_status is null
      or ci.status = target_status
    )
  group by
    ci.id,
    p.display_name,
    p.username
  order by
    case ci.status
      when 'pending' then 1
      when 'approved' then 2
      when 'rejected' then 3
      else 4
    end,
    ci.updated_at desc;
end;
$$;

create or replace function public.admin_set_content_status(
  target_item_id uuid,
  target_status text,
  target_note text
)
returns public.content_items
language plpgsql
security definer
set search_path = public
as $$
declare
  current_row public.content_items;
  updated_row public.content_items;
begin
  if not public.is_admin() then
    raise exception 'administrator access required' using errcode = '42501';
  end if;

  if target_status not in ('pending', 'approved', 'rejected', 'archived') then
    raise exception 'invalid content status' using errcode = '22023';
  end if;

  select *
  into current_row
  from public.content_items
  where id = target_item_id;

  if current_row.id is null then
    raise exception 'content item not found' using errcode = 'P0002';
  end if;

  update public.content_items
  set
    status = target_status,
    moderation_note = nullif(trim(target_note), ''),
    approved_by = case
      when target_status = 'approved' then auth.uid()
      else null
    end,
    approved_at = case
      when target_status = 'approved' then now()
      else null
    end,
    updated_at = now()
  where id = target_item_id
  returning * into updated_row;

  insert into public.content_audit_log (
    content_item_id,
    actor_user_id,
    actor_role,
    action,
    from_status,
    to_status,
    details
  )
  values (
    target_item_id,
    auth.uid(),
    'admin',
    'status_changed',
    current_row.status,
    target_status,
    case
      when target_note is null or trim(target_note) = '' then null
      else jsonb_build_object('note', trim(target_note))
    end
  );

  return updated_row;
end;
$$;

