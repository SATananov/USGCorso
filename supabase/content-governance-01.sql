create or replace function public.create_content_item(
  target_section text,
  target_content_type text,
  target_title text,
  target_body text,
  target_context_type text,
  target_context_id uuid
)
returns public.content_items
language plpgsql
security definer
set search_path = public
as $$
declare
  created_row public.content_items;
begin
  if auth.uid() is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  insert into public.content_items (
    owner_user_id,
    section_key,
    content_type,
    title,
    body,
    context_type,
    context_id,
    status
  )
  values (
    auth.uid(),
    target_section,
    target_content_type,
    nullif(trim(target_title), ''),
    nullif(trim(target_body), ''),
    nullif(trim(target_context_type), ''),
    target_context_id,
    case
      when public.is_admin() then 'approved'
      else 'pending'
    end
  )
  returning * into created_row;

  if public.is_admin() then
    update public.content_items
    set
      approved_by = auth.uid(),
      approved_at = now()
    where id = created_row.id
    returning * into created_row;
  end if;

  insert into public.content_audit_log (
    content_item_id,
    actor_user_id,
    actor_role,
    action,
    to_status
  )
  values (
    created_row.id,
    auth.uid(),
    case when public.is_admin() then 'admin' else 'user' end,
    'created',
    created_row.status
  );

  return created_row;
end;
$$;

create or replace function public.update_my_content_item(
  target_item_id uuid,
  target_title text,
  target_body text,
  target_content_type text
)
returns public.content_items
language plpgsql
security definer
set search_path = public
as $$
declare
  current_row public.content_items;
  updated_row public.content_items;
begin
  select *
  into current_row
  from public.content_items
  where id = target_item_id
    and owner_user_id = auth.uid();

  if current_row.id is null then
    raise exception 'content item not found or access denied' using errcode = '42501';
  end if;

  update public.content_items
  set
    title = nullif(trim(target_title), ''),
    body = nullif(trim(target_body), ''),
    content_type = target_content_type,
    status = 'pending',
    moderation_note = null,
    approved_by = null,
    approved_at = null,
    updated_at = now()
  where id = target_item_id
  returning * into updated_row;

  insert into public.content_audit_log (
    content_item_id,
    actor_user_id,
    actor_role,
    action,
    from_status,
    to_status
  )
  values (
    target_item_id,
    auth.uid(),
    'user',
    'edited',
    current_row.status,
    updated_row.status
  );

  return updated_row;
end;
$$;

