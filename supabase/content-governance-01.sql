create table if not exists public.content_items (
  id uuid primary key default gen_random_uuid(),
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  section_key text not null,
  content_type text not null,
  title text,
  body text,
  context_type text,
  context_id uuid,
  status text not null default 'pending',
  moderation_note text,
  approved_by uuid references auth.users(id) on delete set null,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint content_items_section_check
    check (
      section_key in (
        'home',
        'my_corso',
        'places',
        'knowledge',
        'community',
        'services',
        'events',
        'corso_match',
        'about'
      )
    ),
  constraint content_items_type_check
    check (
      content_type in (
        'article',
        'text',
        'image',
        'document',
        'brochure',
        'event',
        'profile',
        'post',
        'other'
      )
    ),
  constraint content_items_status_check
    check (
      status in (
        'pending',
        'approved',
        'rejected',
        'archived'
      )
    ),
  constraint content_items_title_length
    check (title is null or char_length(title) <= 180),
  constraint content_items_body_length
    check (body is null or char_length(body) <= 20000),
  constraint content_items_note_length
    check (moderation_note is null or char_length(moderation_note) <= 1000)
);

