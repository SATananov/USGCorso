create or replace function public.admin_list_content_audit(
  target_limit integer
)
returns table (
  id bigint,
  content_item_id uuid,
  actor_user_id uuid,
  actor_display_name text,
  actor_username text,
  actor_role text,
  action text,
  from_status text,
  to_status text,
  details jsonb,
  created_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'administrator access required' using errcode = '42501';
  end if;

  return query
  select
    log.id,
    log.content_item_id,
    log.actor_user_id,
    p.display_name,
    p.username,
    log.actor_role,
    log.action,
    log.from_status,
    log.to_status,
    log.details,
    log.created_at
  from public.content_audit_log log
  left join public.profiles p
    on p.id = log.actor_user_id
  order by log.created_at desc
  limit greatest(1, least(coalesce(target_limit, 100), 500));
end;
$$;

